"""Role-scoped narratives generated from the model. Do not hand-edit the output."""

from __future__ import annotations

import re

from scl.model import Loaded

GENERATED = "<!-- GENERATED by scl export. Do not hand-edit. Source: meta/iomr-model -->"
POWER_CATEGORIES = {"functional", "governance", "operational"}
APPENDIX_AT = 8

ROLES = {
    "developer": {
        "knows": "the stack, the patterns, and how code is built",
        "next": "understand, then build within these constraints",
        "scope": "all",
    },
    "tester": {
        "knows": "how to verify behaviour and what evidence looks like",
        "next": "understand, then verify the model is met",
        "scope": "all",
    },
    "power-user": {
        "knows": "the business domain, not the implementation",
        "next": "understand, then confirm the system does the right thing",
        "scope": "business",
    },
}


def _words(text: str) -> int:
    return len(re.findall(r"\S+", text))


def budget(text: str, slice_peaks: list[int]) -> tuple[int, str]:
    minutes = max(1, round(_words(text) / 200))
    peak = max(slice_peaks) if slice_peaks else 0
    if minutes > 15 or peak > APPENDIX_AT:
        load = "H"
    elif minutes <= 4 and peak <= 4:
        load = "L"
    else:
        load = "M"
    return minutes, load


def _included(requirement: dict, role: str) -> bool:
    if ROLES[role]["scope"] == "all":
        return True
    metadata = requirement.get("metadata") or {}
    if metadata.get("businessConsequence"):
        return True
    return metadata.get("category") in POWER_CATEGORIES


def _human(outcome: dict) -> bool:
    evaluation = (outcome.get("metadata") or {}).get("evaluation")
    return evaluation in {"human-judgement", "mixed", "vector"}


def render_role(loaded: Loaded, role: str) -> tuple[str, str | None]:
    """Return the main narrative and an optional appendix."""
    if role not in ROLES:
        raise SystemExit(f"unknown role {role}")
    profile = ROLES[role]
    by_id = loaded.by_id
    outcomes = [node for node in loaded.nodes if node["type"] == "Outcome"]
    models = [node for node in loaded.nodes if node["type"] == "Model"]
    requirements = [node for node in loaded.nodes if node["type"] == "Requirement"]
    models.sort(key=lambda node: (node.get("metadata") or {}).get("order", 0))

    def serves(model_id: str) -> list[dict]:
        ids = [rel["to"] for rel in loaded.relationships if rel["type"] == "serves" and rel["from"] == model_id]
        return [by_id[item] for item in ids if item in by_id]

    def specifies(model_id: str) -> list[dict]:
        ids = [rel["from"] for rel in loaded.relationships if rel["type"] == "specifies" and rel["to"] == model_id]
        return [by_id[item] for item in ids if item in by_id]

    main_slices: list[tuple[dict, list[dict], list[dict]]] = []
    appendix_slices: list[tuple[dict, list[dict], list[dict]]] = []
    for model in models:
        kept = [req for req in specifies(model["id"]) if _included(req, role)]
        if not kept and role != "developer":
            # Still keep a slice when a human-judgement outcome needs to stay visible.
            judged = [item for item in serves(model["id"]) if _human(item)]
            if not judged:
                continue
        bucket = appendix_slices if len(kept) > APPENDIX_AT else main_slices
        bucket.append((model, serves(model["id"]), kept))

    def slice_body(model: dict, served: list[dict], reqs: list[dict], standalone: bool) -> str:
        metadata = model.get("metadata") or {}
        title = metadata.get("sliceTitle") or model["name"]
        lines = [f"## {title}", ""]
        if standalone:
            lines.append(f"This slice stands alone. Model `{model['id']}` ({model.get('status', 'unspecified')}).")
            lines.append("")
        outcome_bits = []
        for outcome in served:
            mark = " ⚖" if _human(outcome) else ""
            outcome_bits.append(f"`{outcome['id']}`{mark}")
        if outcome_bits:
            lines.append("Outcomes: " + ", ".join(outcome_bits) + ".")
            lines.append("")
        lines.append(model["description"])
        lines.append("")
        for req in reqs:
            req_meta = req.get("metadata") or {}
            if role == "power-user" and req_meta.get("businessConsequence"):
                text = req_meta["businessConsequence"]
            elif role == "power-user":
                text = req["description"]
            elif role == "tester":
                text = f"Acceptance: {req_meta.get('acceptance', req['description'])} — {req['description']}"
            else:
                text = f"{req['description']} Acceptance: {req_meta.get('acceptance', '')}"
            status = req.get("status", "")
            lines.append(
                f"- `{req['id']}` ({req_meta.get('category', 'unspecified')}, {status}). {text}"
            )
        if not reqs:
            lines.append("The constraints for this slice are technical and are not restated here.")
            for outcome in served:
                consequence = (outcome.get("metadata") or {}).get("businessConsequence")
                if consequence:
                    lines.append(f"What it means: {consequence}")
        lines.append("")
        return "\n".join(lines)

    def document(slices, heading: str, intro: str) -> str:
        body_parts = [slice_body(model, served, reqs, standalone=False) for model, served, reqs in slices]
        judgements = []
        for outcome in outcomes:
            if not _human(outcome):
                continue
            mark = (outcome.get("metadata") or {}).get("businessConsequence") or outcome["description"]
            judgements.append(f"- `{outcome['id']}` ⚖ {mark}")
        parts = [
            GENERATED,
            "",
            f"# {heading}",
            "",
            intro,
            "",
            "## Judgements a person owns",
            "",
            "Validation cannot certify these. A human owns the judgement.",
            "",
            *judgements,
            "",
            *body_parts,
        ]
        draft = "\n".join(parts).rstrip() + "\n"
        peaks = [len(reqs) for _model, _served, reqs in slices] or [0]
        minutes, load = budget(draft, peaks)
        header = (
            f"> **Reader:** {role}. **Already knows:** {profile['knows']}. "
            f"**Next step:** {profile['next']}. "
            f"**Human-constraint budget:** ~{minutes} min read · cognitive load **{load}**."
        )
        return draft.replace(intro, header + "\n\n" + intro, 1)

    main = document(
        main_slices,
        f"SCL for a {role}",
        "The model is the source of truth. This narrative is generated from it.",
    )
    appendix = None
    if appendix_slices:
        appendix = document(
            appendix_slices,
            f"SCL for a {role} — appendix",
            "Read this when you are building the planned slice. It is a separate touchpoint.",
        )
        pointer = [
            "",
            "## Planned slice, held in a separate touchpoint",
            "",
            "The planned verification and test-adapter constraints are in the appendix. "
            "That document is useful on its own when you start that build. "
            "The judgements for that slice stay listed above.",
            "",
        ]
        main = main.rstrip() + "\n" + "\n".join(pointer)
        # Recompute the main budget after the pointer, without the appendix peak.
        peaks = [len(reqs) for _model, _served, reqs in main_slices] or [0]
        minutes, load = budget(main, peaks)
        main = re.sub(
            r"\*\*Human-constraint budget:\*\* ~\d+ min read · cognitive load \*\*[HML]\*\*",
            f"**Human-constraint budget:** ~{minutes} min read · cognitive load **{load}**",
            main,
            count=1,
        )
    return main, appendix


def traceability(loaded: Loaded) -> str:
    lines = [
        GENERATED,
        "",
        "# SCL traceability",
        "",
        "Relationships point up the chain: Requirement specifies Model serves Outcome delivers Intent.",
        "",
    ]
    by_id = loaded.by_id
    for kind in ("Intent", "Outcome", "Model", "Requirement", "Actor", "System", "Policy", "Decision", "Project"):
        rows = sorted((node for node in loaded.nodes if node["type"] == kind), key=lambda node: node["id"])
        if not rows:
            continue
        lines.append(f"## {kind}")
        lines.append("")
        for node in rows:
            status = node.get("status", "")
            lines.append(f"- `{node['id']}` ({status}) {node['name']}")
        lines.append("")
    lines.append("## Relationships")
    lines.append("")
    for rel in sorted(loaded.relationships, key=lambda item: item["id"]):
        lines.append(f"- `{rel['id']}` {rel['type']}: `{rel['from']}` → `{rel['to']}`")
    lines.append("")
    # Touch by_id so a missing endpoint would have already failed structural checks.
    _ = by_id
    return "\n".join(lines).rstrip() + "\n"


def mermaid_trace(loaded: Loaded, intent_id: str) -> str:
    by_id = loaded.by_id
    if intent_id not in by_id:
        raise SystemExit(f"unknown record {intent_id}")
    outcomes = [rel["from"] for rel in loaded.relationships if rel["type"] == "delivers" and rel["to"] == intent_id]
    lines = ["flowchart TD", f"  {intent_id}[{intent_id}]"]
    for outcome_id in outcomes:
        lines.append(f"  {outcome_id}[{outcome_id}] --> {intent_id}")
        models = [rel["from"] for rel in loaded.relationships if rel["type"] == "serves" and rel["to"] == outcome_id]
        for model_id in models:
            lines.append(f"  {model_id}[{model_id}] --> {outcome_id}")
            reqs = [rel["from"] for rel in loaded.relationships if rel["type"] == "specifies" and rel["to"] == model_id]
            for req_id in reqs:
                lines.append(f"  {req_id}[{req_id}] --> {model_id}")
    return "\n".join(lines) + "\n"


def mermaid_sequence(loaded: Loaded, model_id: str) -> str:
    model = loaded.by_id.get(model_id)
    if model is None or model.get("type") != "Model":
        raise SystemExit(f"unknown model {model_id}")
    lines = ["sequenceDiagram"]
    for step in model.get("steps") or []:
        lines.append(f"  {step['from']}->>{step['to']}: {step['message']}")
    if len(lines) == 1:
        lines.append(f"  note over {model_id}: no ordered steps recorded")
    return "\n".join(lines) + "\n"
